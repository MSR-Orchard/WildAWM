"""Codex CLI backend: subprocess-based, driven per turn by the in-container agent adapter."""

from pathlib import Path

from wildawm.const_config import AGENT_INTERNAL_PORT, LLM_PROXY_PORT

from .base import AgentBackend


class CodexBackend(AgentBackend):
    KIND = "codex"

    def internal_port(self) -> int:
        return AGENT_INTERNAL_PORT

    def host_port_base(self) -> int:
        return 9200

    def prepare(self, world_id: str, project_root: Path, state_dir: Path,
                model: dict) -> None:
        config_dir = state_dir / "agent-config"
        config_dir.mkdir(parents=True, exist_ok=True)

        model_name = model["api_model"]
        # The in-container Responses->Chat proxy forwards upstream; config.toml needs model + proxy.

        reasoning_lines = ""
        effort = (model.get("reasoning_effort") or "").strip()
        if effort and effort != "none":
            reasoning_lines = "model_supports_reasoning_summaries = true\n"
            # Codex's native flag lacks `max`; the in-container proxy injects it upstream instead.
            if effort != "max":
                reasoning_lines = (
                    f'model_reasoning_effort = "{effort}"\n'
                    + reasoning_lines
                )
        context_line = ""
        if model.get("context_window"):
            context_line = f'model_context_window = {int(model["context_window"])}\n'
        toml_content = f"""# Auto-generated by WildAWM dashboard
model = "{model_name}"
model_provider = "wildawm-proxy"
{reasoning_lines}{context_line}
[model_providers.wildawm-proxy]
name = "WildAWM Responses→Chat Proxy"
base_url = "http://localhost:{LLM_PROXY_PORT}/v1"
env_key = "OPENAI_API_KEY"
wire_api = "responses"
"""
        (config_dir / "codex-config.toml").write_text(toml_content)
